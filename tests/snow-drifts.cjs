const assert=require('node:assert/strict');
const SnowDrifts=require('../snow-drifts.js');
const snow=new SnowDrifts(null);snow.resize(1200,800);
snow.sync([{key:'lower',x:40,y:300,width:200},{key:'upper',x:40,y:100,width:200}]);
const mass=key=>Array.from(snow.surfaces.get(key).heights).reduce((a,b)=>a+b,0);
const before=mass('upper');
assert.equal(snow.deposit(140,80,120,5),true);assert.ok(mass('upper')>before);
assert.equal(snow.deposit(900,80,120,5),false);
assert.equal(snow.deposit(140,150,180,5),false,'flakes below a ledge do not land upwards');
for(let n=0;n<1000;n++)snow.deposit(140,0,500,12);
assert.ok([...snow.surfaces.get('upper').heights].every(h=>h<=14));
const original=Array.from(snow.surfaces.get('upper').heights), centerMass=mass('upper'), lower=mass('lower');
snow.brush(125,96,0);snow.brush(150,96,40);snow.brush(130,96,80);snow.brush(135,88,120);
assert.ok(Math.abs(mass('upper')-centerMass)<.0001,'stirring in the middle preserves snow mass');
assert.notDeepEqual(Array.from(snow.surfaces.get('upper').heights),original,'stirring reshapes the mound');
assert.equal(snow.debris.length,0,'the middle does not spawn falling snow');
assert.equal(mass('lower'),lower,'center stirring leaves other ledges untouched');
const stirredMass=mass('upper');snow.step(1);
const lowerAfterStep=mass('lower');
assert.ok(mass('upper')>=stirredMass-.0001,'settling does not erase a piled-up mound');
snow.forgetPointer();snow.brush(80,96,0);
for(let x=90;x<=250;x+=10)snow.brush(x,96,x*2);
assert.ok(mass('upper')<centerMass,'pushing beyond the edge sheds snow');
assert.equal(mass('lower'),lowerAfterStep,'other ledges are unaffected');
assert.ok(snow.spills.length > 0 && snow.spills.every(spill=>spill.direction===1 && spill.age===0));
assert.equal(snow.debris.length,0,'the snow crosses the rim before breaking into debris');
snow.step(3);
assert.equal(snow.debris.length,0);
snow.step(3);
assert.ok(snow.debris.length>0 && snow.debris.length<=140,'the falling stream releases debris');
assert.ok(snow.spills.length>0,'the stream tapers while releasing particles');
const narrow=new SnowDrifts(null);narrow.resize(1200,800);narrow.sync([{key:'narrow',x:20,y:100,width:80}]);
const narrowMass=()=>[...narrow.surfaces.get('narrow').heights].reduce((a,b)=>a+b,0);
const start=narrowMass();narrow.brush(55,95,0);narrow.brush(62,95,40);narrow.brush(62,90,80);
assert.ok(Math.abs(narrowMass()-start)<.0001,'narrow widgets also preserve snow in the middle');
assert.equal(narrow.debris.length,0);
snow.sync([{key:'upper',x:140,y:170,width:300}]);
assert.equal(snow.surfaces.size,1);assert.equal(snow.surfaces.get('upper').y,170.5);
for(let n=0;n<120;n++)snow.step(2);
assert.equal(snow.debris.length,0,'debris expires');snow.clear();assert.equal(snow.surfaces.size,0);
console.log('PASS: snow landing, center stirring conserves mass, edge-only shedding, narrow ledges and particle lifecycle');

for(const width of [80,200,540])for(const direction of [-1,1])for(const stride of [.25,2,12,1000]){
  const plow=new SnowDrifts(null);plow.resize(1600,900);plow.sync([{key:'ledge',x:100,y:150,width}]);
  const surface=plow.surfaces.get('ledge');
  for(let n=0;n<30;n++)for(let x=110;x<100+width-10;x+=8)plow.deposit(x,100,160,8);
  const mass=()=>[...surface.heights].reduce((a,b)=>a+b,0), before=mass();
  const start=direction>0?surface.x-40:surface.x+surface.width+40;
  const end=direction>0?surface.x+surface.width+40:surface.x-40;
  plow.brush(start,146);
  for(let x=start+direction*stride;direction>0?x<end:x>end;x+=direction*stride)plow.brush(x,146);
  plow.brush(end,146);
  assert.ok(mass()<before*.01,'one full sweep clears '+width+'px ledge in direction '+direction+' with '+stride+'px events');
  assert.ok(plow.spills.length>0 && plow.spills.length<=12);
}
console.log('PASS: one-pass clearing on narrow and wide ledges, both directions, slow and sparse pointer events');

const contact=new SnowDrifts(null);contact.resize(1200,800);contact.sync([{key:'contact',x:100,y:150,width:200}]);
const bank=contact.surfaces.get('contact');bank.heights.fill(0);
const middle=Math.floor(bank.heights.length/2);bank.heights[middle]=10;
const center=bank.x+middle/(bank.heights.length-1)*bank.width;
contact.brush(center-10,146,0);contact.brush(center-4,146,40);
const pushed=Array.from(bank.heights);
contact.brush(center-16,146,80);
assert.deepEqual(Array.from(bank.heights),pushed,'reversing away from a bank does not pull it after the cursor');
assert.equal(contact.debris.length,0);
console.log('PASS: snow is pushed by contact and is not magnetically dragged on reversal');

const powder = new SnowDrifts(null);
powder.resize(1200, 800);
powder.sync([{ key: 'powder', x: 100, y: 150, width: 200 }]);
const profile = powder.surfaces.get('powder').heights;
profile.fill(6, 1, -1);
const volume = () => profile.reduce((total, height) => total + height, 0);
const packed = volume();
powder.brush(140, 146, 0);
powder.brush(180, 146, 8);
assert.ok(powder.debris.length > 0 && powder.debris.length <= 5);
assert.ok(powder.debris.every(p => p.powder && p.x > 120 && p.x < 195));
assert.ok(volume() < packed && packed - volume() <= .601, 'only a small amount becomes dust');
const burst = powder.debris.length;
powder.forgetPointer();
powder.brush(140, 80, 10);
powder.brush(190, 80, 14);
assert.equal(powder.debris.length, burst, 'a quick pass away from snow does not release dust');

profile.fill(0);
const peak = Math.floor(profile.length / 2);
profile[peak] = 24;
powder.step(1);
assert.ok(profile[peak] < 24 && profile[peak + 1] > 0, 'steep slopes settle downhill');
assert.ok(Math.abs(volume() - 24) < .0001, 'settling conserves volume');
for (let frame = 0; frame < 40; frame++) powder.step(1, .2);
assert.equal(powder.debris.length, 0, 'powder fades quickly');
console.log('PASS: rapid contact releases a small puff and steep slopes settle without losing volume');

const landing = new SnowDrifts(null);
landing.resize(800, 600);
landing.sync([{ key: 'source', x: 100, y: 100, width: 150 }, { key: 'receiver', x: 150, y: 165, width: 220 }]);
const source = landing.surfaces.get('source');
const receiver = landing.surfaces.get('receiver');
const receiverVolume = () => receiver.heights.reduce((total, height) => total + height, 0);
for (let frame = 0; frame < 600; frame++) landing.step(1);
assert.equal(receiverVolume(), 0, 'a fresh ledge stays bare without impacts');
assert.equal(landing.deposit(20, 135, 175, 4, 180), false, 'entering a ledge below the rim does not deposit');
assert.equal(landing.deposit(145, 140, 185, 4, 220), true, 'a diagonal flake lands where it crosses the rim');
assert.ok(receiverVolume() > 0);
receiver.heights.fill(0);
landing.scatter(225, source.y, 1, 1, 0, false, source);
const fragment = landing.debris[0];
assert.equal(receiverVolume(), 0, 'releasing a fragment does not deposit it');
Object.assign(fragment, { x: 225, y: 145, vx: 0, vy: 5 });
landing.step(1);
assert.equal(receiverVolume(), 0, 'a fragment still in the air adds nothing');
for (let frame = 0; frame < 6; frame++) landing.step(1);
assert.equal(landing.debris.length, 0, 'the fragment is removed when it lands');
assert.ok(Math.abs(receiverVolume() - 1) < .0001, 'the lower ledge receives the fragment volume once');
receiver.heights.fill(0);
landing.spill(source, 8, 1, 1);
for (let frame = 0; frame < 22; frame++) landing.step(1);
assert.equal(landing.spills.length, 0, 'the stream fully breaks apart');
assert.ok(landing.debris.length > 1, 'the stream releases several successive fragments');
assert.ok(Math.abs(landing.debris.reduce((sum, p) => sum + p.volume, 0) - 8) < .0001,
  'the stream transfers its volume to the falling fragments');
console.log('PASS: accumulation requires impacts and a snow stream breaks into falling fragments');
